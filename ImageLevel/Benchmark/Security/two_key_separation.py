"""
Security -- §7.3: Two-Key Separation
=======================================
Tests that positions generated by two different keys have zero/negligible overlap,
and that extracting with the wrong key produces unreadable output.

Charts:
  results/two_key_separation_bar.png  -- position overlap for key pairs (bar)
  results/two_key_separation_line.png -- extraction success vs key distance (line)
  results/two_key_separation.json     -- raw data

Run:
    cd ImageLevel
    python Benchmark/Security/two_key_separation.py
"""

import sys
import tempfile
import os
from pathlib import Path

BENCH_DIR   = Path(__file__).resolve().parent.parent
PROJECT_DIR = BENCH_DIR.parent
sys.path.insert(0, str(PROJECT_DIR))
sys.path.insert(0, str(BENCH_DIR))

import numpy as np
import matplotlib.pyplot as plt
from common import (
    list_dicom_files, load_dicom_cover,
    save_figure, save_json, results_dir,
    CHAOS_KEY,
)

RDIR = results_dir("Security")

# Key pairs to test
KEY_PAIRS = [
    ("Key A (correct)",       CHAOS_KEY),
    ("Key B (wrong string)",  "wrong_chaos_key_v1"),
    ("Key C (similar prefix)","zkdicom_chaos_key_v2"),
    ("Key D (random)",        "totally_different_key_9823jf"),
    ("Key E (empty-like)",    "x"),
]
N_POSITIONS = 2000


def _get_positions(cover, roi_mask, key_str, n):
    from src.zk_stego.dicom_handler import DicomStego
    from src.zk_stego.utils import generate_chaos_key_from_secret
    h, w = cover.shape
    key_int = generate_chaos_key_from_secret(key_str)
    x0, y0 = DicomStego._key_start(key_int, w, h, roi_mask)
    pos_list = DicomStego._roi_positions(
        cover, roi_mask, x0, y0, key_int, n,
        sort_by_entropy=False, exclude=None,
    )
    return set(map(tuple, pos_list))


def _jaccard(a, b):
    if not a and not b:
        return 1.0
    return len(a & b) / len(a | b)


def _try_extract(dcm_path: str, stego_path: str, key: str) -> dict:
    """Try to extract from stego_path using key. Return success/failure + details."""
    try:
        from src.zk_stego.dicom_handler import DicomStego
        ds = DicomStego()
        result = ds.extract(stego_path, chaos_key=key, verbose=False)
        if result and result.get("success") is True:
            return {"success": True, "status": "ok"}
        return {"success": False, "status": result.get("error", "unknown") if result else "none"}
    except Exception as e:
        return {"success": False, "status": f"exception: {type(e).__name__}"}


def run(verbose: bool = True) -> dict:
    dcm_files = list_dicom_files()
    dcm_path  = str(dcm_files[0])
    cover, fname = load_dicom_cover(dcm_files[0])

    from src.zk_stego.dicom_handler import DicomHandler
    roi_mask = DicomHandler.detect_roi(cover)

    if verbose:
        print(f"Two-Key Separation on: {fname}\n")

    # ── 1. Position overlap between all key pairs ─────────────────────────────
    positions = {}
    for label, key in KEY_PAIRS:
        positions[label] = _get_positions(cover, roi_mask, key, N_POSITIONS)
        if verbose:
            print(f"  Positions for {label[:30]}: {len(positions[label])} positions")

    ref_label = KEY_PAIRS[0][0]
    ref_pos   = positions[ref_label]

    overlap_results = {}
    for label, _ in KEY_PAIRS[1:]:
        j = _jaccard(ref_pos, positions[label]) * 100
        overlap_results[label] = round(j, 4)
        if verbose:
            print(f"  Overlap {ref_label[:10]} vs {label[:30]}: {j:.4f}%")

    # ── 2. Extraction test with correct and wrong keys ────────────────────────
    if verbose:
        print("\nEmbedding with Key A and testing extraction with all keys...")

    with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as f:
        stego_tmp = f.name
    try:
        from src.zk_stego.dicom_handler import DicomStego
        DicomStego().embed(dcm_path, stego_tmp, chaos_key=CHAOS_KEY,
                           generate_zk_proof=False, verbose=False)

        extract_results = {}
        for label, key in KEY_PAIRS:
            result = _try_extract(dcm_path, stego_tmp, key)
            extract_results[label] = result
            status = "SUCCESS" if result["success"] else f"FAIL ({result['status']})"
            if verbose:
                print(f"  Extract with {label[:30]:30s}: {status}")
    finally:
        if os.path.exists(stego_tmp):
            os.unlink(stego_tmp)

    # ── Figure 1: Position overlap bar chart ─────────────────────────────────
    fig1, ax1 = plt.subplots(figsize=(10, 5))
    labels = [k for k, _ in KEY_PAIRS[1:]]
    overlaps = [overlap_results[k] for k in labels]
    short_labels = [k.split("(")[1].rstrip(")") for k in labels]
    colors = ["#F44336" if v > 5 else "#4CAF50" for v in overlaps]
    bars = ax1.bar(short_labels, overlaps, color=colors, edgecolor="white", alpha=0.87)
    for bar, val in zip(bars, overlaps):
        ax1.text(bar.get_x() + bar.get_width()/2, val + 0.05,
                 f"{val:.3f}%", ha="center", va="bottom", fontsize=9.5)
    ax1.axhline(5, color="orange", linestyle="--", linewidth=1.2,
                label="5% threshold")
    ax1.axhline(1, color="green", linestyle="--", linewidth=1.2,
                label="1% ideal separation")
    ax1.set_ylabel("Position overlap with Key A (%)")
    ax1.set_title(f"Two-Key Separation: Position Overlap\n"
                  f"Reference = Key A (correct) | {N_POSITIONS} positions")
    ax1.legend(fontsize=9)
    ax1.grid(True, alpha=0.3, axis="y")
    ax1.set_ylim(0, max(max(overlaps) * 1.3, 8))
    plt.tight_layout()
    save_figure(fig1, RDIR / "two_key_separation_bar.png")

    # ── Figure 2: Extraction outcome line ─────────────────────────────────────
    fig2, ax2 = plt.subplots(figsize=(10, 4))
    key_labels  = [k for k, _ in KEY_PAIRS]
    success_bin = [1 if extract_results[k]["success"] else 0 for k in key_labels]
    colors2 = ["#4CAF50" if s else "#F44336" for s in success_bin]
    ax2.bar(range(len(key_labels)), success_bin, color=colors2, edgecolor="white",
            alpha=0.87, width=0.5)
    for i, (k, s) in enumerate(zip(key_labels, success_bin)):
        label = "OK" if s else extract_results[k]["status"][:20]
        ax2.text(i, s + 0.03, label, ha="center", va="bottom", fontsize=9)
    ax2.set_xticks(range(len(key_labels)))
    ax2.set_xticklabels([k.split("(")[1].rstrip(")") for k in key_labels],
                        rotation=20, ha="right", fontsize=9)
    ax2.set_yticks([0, 1])
    ax2.set_yticklabels(["FAIL", "SUCCESS"])
    ax2.set_title(f"Extraction Outcome with Different Keys\n"
                  f"(stego created with Key A = correct key)")
    ax2.grid(True, alpha=0.3, axis="y")
    plt.tight_layout()
    save_figure(fig2, RDIR / "two_key_separation_line.png")

    output = {
        "file":            fname,
        "n_positions":     N_POSITIONS,
        "reference_key":   ref_label,
        "position_overlap_pct": overlap_results,
        "extraction_results":   extract_results,
    }
    save_json(output, RDIR / "two_key_separation.json")
    return output


if __name__ == "__main__":
    run(verbose=True)
