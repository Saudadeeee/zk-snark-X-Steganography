# -- helpers --------------------------------------------------------------- #

def load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def num(value: Any, digits: int = 2) -> str:
    if value is None:
        return "--"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    if isinstance(value, int) and abs(value) >= 10_000:
        return f"{value:,}".replace(",", r"\,")
    return str(value)


def video_info(name: str) -> tuple[str, str, int, str]:
    """(clip, resolution, qp, note) from an encoded file name or case name."""
    match = re.match(r"(?P<clip>[a-z_]+?)_?(?P<res>4cif|cif)_q(?P<qp>\d+)", name)
    if match is None:
        match = re.match(r"(?P<clip>[a-z_]+?)(?P<loop>3000f)_q(?P<qp>\d+)", name)
        clip = match["clip"]
        return CLIP_NAMES.get(clip, clip.title()), "CIF", int(match["qp"]), "looped"
    clip = match["clip"].removesuffix("_")
    return CLIP_NAMES.get(clip, clip.title()), match["res"].upper(), int(match["qp"]), ""


def table(body: list[str], *, columns: str, header: str, caption: str, label: str,
          wide: bool = False, size: str = r"\footnotesize", notes: str = "") -> str:
    env = "table*" if wide else "table"
    lines = [
        f"% Generated by docs/paper/tools/make_tables.py -- do not edit by hand.",
        f"\\begin{{{env}}}[t]",
        "\\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        size,
        "\\setlength{\\tabcolsep}{3.2pt}",
        "\\fitwidth{%",
        f"\\begin{{tabular}}{{{columns}}}",
        "\\toprule",
        header + r" \\",
        "\\midrule",
        *[row if row.endswith(("\\\\", "\\midrule")) else row + r" \\" for row in body],
        "\\bottomrule",
        "\\end{tabular}}",
    ]
    if notes:
        lines.append(f"\\par\\smallskip\\parbox{{\\linewidth}}{{\\scriptsize {notes}}}")
    lines.append(f"\\end{{{env}}}")
    return "\n".join(lines) + "\n"


# -- capacity -------------------------------------------------------------- #

def capacity_table(results: Path) -> str:
    rows = []
    for path in sorted(results.glob("capacity_*.json")):
        for scan in load(path):
            if scan.get("carrier", "magnitude") != "magnitude":
                continue
            clip, res, qp, _ = video_info(scan["video"])
            if "inband" in path.stem and any(r["video"] == scan["video"] for r in rows):
                continue
            bits = scan["carrier_bits_per_segment"]
            rows.append({
                "video": scan["video"], "clip": clip, "res": res, "qp": qp, "frames": scan["frames"],
                "scanned": scan["segments_scanned"], "total": scan["segments_total"],
                "min": min(bits) / 1000, "mean": sum(bits) / len(bits) / 1000,
                "reg": scan["registered_segments_needed_at_min_chunk"],
                "inb": scan["in_band_segments_needed_at_min_chunk"],
                "reg_fit": scan["registered_fits_estimate"], "inb_fit": scan["in_band_fits_estimate"],
            })
    unique: dict[str, dict[str, Any]] = {}
    for row in rows:
        unique.setdefault(row["video"], row)
    ordered = sorted(unique.values(), key=lambda r: (r["res"] != "CIF", r["qp"] != 22, r["mean"]))

    def need(segments: int, fits: bool, total: int) -> str:
        text = f"{segments * 100}"
        return text if fits else text + r"$^{\dagger}$"

    body = [
        f"{r['clip']} & {r['res']} & {r['qp']} & {r['frames']} & {r['scanned']}/{r['total']} & "
        f"{r['min']:.1f} & {r['mean']:.1f} & {need(r['reg'], r['reg_fit'], r['total'])} & "
        f"{need(r['inb'], r['inb_fit'], r['total'])}"
        for r in ordered
    ]
    return table(
        body, columns="lllrrrrrr",
        header=("Clip & Res. & QP & Frames & Seg. & \\multicolumn{2}{c}{kbit/100 fr.} & "
                "\\multicolumn{2}{c}{Frames needed} \\\\\n\\cmidrule(lr){6-7}\\cmidrule(lr){8-9}\n"
                " & & & & scanned & min & mean & reg. & in-band"),
        caption=("Stable, patchability-checked magnitude carriers (all-intra, x264 Baseline/CAVLC). "
                 "Seg.\\ scanned: 100-frame segments measured out of the clip's total; unscanned segments "
                 "are extrapolated from the scanned ones. Frames needed: segments required at the smallest "
                 "feasible chunk size; "
                 "$^{\\dagger}$\\,more than the clip has."),
        label="tab:capacity",
    )


# -- end-to-end ------------------------------------------------------------ #

def _e2e_case_rows(results: Path) -> tuple[list[dict[str, Any]], list[tuple[str, str]]]:
    done, missing = [], []
    for path in sorted(results.glob("e2e_*.json")):
        report = load(path)
        if "input_video" not in report or report.get("carrier") == "t1":
            continue
        done.append({"case": path.stem.removeprefix("e2e_"), **report})
    if CASES.exists():
        names = {row["case"] for row in done}
        for case in load(CASES):
            name = case["name"]
            if case.get("carrier") == "t1" or "_d" in name.split("_reg")[-1] or name in names:
                continue
            skipped = results / f"e2e_{name}.skipped.json"
            reason = load(skipped)["reason"] if skipped.exists() else None
            missing.append((name, reason))
    return done, missing


def e2e_table(results: Path) -> str:
    done, missing = _e2e_case_rows(results)

    def key(row: dict[str, Any]) -> tuple:
        clip, res, qp, note = video_info(row["case"])
        return (row["mode"].startswith("in-band"), res != "CIF", bool(note), clip, qp)

    body = []
    for row in sorted(done, key=key):
        clip, res, qp, note = video_info(row["case"])
        quality, timings = row.get("frame_quality") or {}, row["timings_s"]
        mode = "reg." if row["mode"].startswith("registered") else "in-band"
        checks = "R,T" if row.get("replay_rejected") and row.get("tamper_rejected") else "--"
        link = row.get("credential_linkage") or {}
        if link.get("linked_to_credential") and link.get("disclosure_verifies"):
            checks = (checks + ",L,D") if checks != "--" else "L,D"
        label = clip + (r"$^{\ast}$" if note else "")
        body.append(
            f"{label} & {res} & {qp} & {mode} & {quality.get('frames', '--')} & {row['segments_used']} & "
            f"{num(row['carriers_used'])} & {quality.get('frames_modified', '--')} & "
            f"{num(quality.get('luma_psnr_modified_frames_db'))} & {num(quality.get('luma_psnr_worst_frame_db'))} & "
            f"{num(quality.get('luma_psnr_all_frames_db'))} & {num((row.get('decoded_quality') or {}).get('ssim_all'), 5)} & "
            f"{timings.get('embed_s', 0):.0f} & {timings.get('verify_s', 0):.0f} & "
            f"{num(row['blind_video_only_verification'])} & {checks}"
        )
    for name, reason in missing:
        clip, res, qp, _ = video_info(name)
        mode = "in-band" if "inband" in name else "reg."
        status = (f"\\multicolumn{{12}}{{l}}{{skipped by the sweep: {reason}}}" if reason
                  else f"\\multicolumn{{12}}{{l}}{{{TODO} pending run}}")
        body.append(f"{clip} & {res} & {qp} & {mode} & {status}")
    return table(
        body, columns="llrlrrrrrrrrrrll", wide=True,
        header=("Clip & Res. & QP & Mode & Frames & Seg. & Carriers & Mod. fr. & "
                "PSNR$_{\\mathrm{mod}}$ & PSNR$_{\\min}$ & PSNR$_{\\mathrm{all}}$ & SSIM & "
                "Embed (s) & Verify (s) & Verified & Checks"),
        caption=("End-to-end runs with the magnitude carrier. Every completed run was verified from the "
                 "stego video alone. PSNR is luma PSNR (dB) against the decoded cover, computed from the "
                 "mean MSE over modified frames (mod), the worst frame (min) and all frames (all); SSIM is "
                 "over the whole video. Checks: R = replay of the consumed session rejected, T = a one-bit "
                 "change of the stego file rejected, L = linkage proof to a credential verified and a "
                 "different credential rejected, D = later disclosure of the payload verified; -- = not "
                 "exercised in that run. $^{\\ast}$\\,300-frame source looped to 3\\,000 frames; these two "
                 "runs were executed concurrently, so their times are inflated."),
        label="tab:e2e",
    )


# -- steganalysis ---------------------------------------------------------- #

def steg_classical_table(results: Path) -> str:
    body = []
    for path in sorted(results.glob("steg_*.json")):
        stem = path.stem.removeprefix("steg_")
        e2e = results / f"e2e_{stem}.json"
        if not e2e.exists() or load(e2e).get("carrier") == "t1":
            continue
        report = load(path)
        clip, res, qp, note = video_info(stem)
        mode = "in-band" if "inband" in stem else "reg."
        pixel = report["pixel_reference_detectors"]
        body.append(
            f"{clip}{'$^{\\ast}$' if note else ''} & {res} & {qp} & {mode} & {report['frames_analysed']} & "
            f"{num(report['pairs_of_values_attack']['cover']['embedding_probability'], 3)} / "
            f"{num(report['pairs_of_values_attack']['stego']['embedding_probability'], 3)} & "
            f"{num(report['magnitude_histogram']['p_value'], 3)} & "
            f"{num(report['trailing_one_signs']['p_value'], 3)} & "
            f"{num(report['per_scan_position_signs']['p_value'], 3)} & "
            f"{pixel['spa_cover']:.4f} / {pixel['spa_stego']:.4f}"
        )
    return table(
        body, columns="llrlrrrrrr",
        header=("Clip & Res. & QP & Mode & Frames & PoV $P$ (c/s) & Mag.\\ $p$ & T1 $p$ & Pos.\\ $p$ & "
                "SPA (c/s)"),
        caption=("Targeted classical steganalysis against the exact cover (magnitude carrier). PoV: "
                 "Westfeld--Pfitzmann embedding probability on carrier magnitudes for cover/stego; "
                 "Mag., T1, Pos.: $p$-values of two-sample tests on the magnitude histogram, trailing-one "
                 "signs and per-scan-position signs ($p<0.05$ would indicate detection); SPA: sample-pair "
                 "estimate on decoded luma for cover/stego."),
        label="tab:steg-classical", wide=True,
    )


def steg_ml_table(results: Path) -> str:
    ml = load(results / "ml_eval.json")
    loco, paired = ml["protocols"]["leave_one_clip_out"], ml["protocols"]["paired_half_split"]
    names = {"coefficient": "Coefficient (340)", "pixel": "Pixel, reduced SRM (500)", "combined": "Combined (840)"}
    body = []
    for feature, label in names.items():
        for detector, short in (("logistic", "logistic"), ("fld_ensemble", "FLD ens.")):
            key = f"{feature}/{detector}"
            folds = [fold["p_e"] for fold in loco[key]["folds"]]
            body.append(
                f"{label if detector == 'logistic' else ''} & {short} & {loco[key]['p_e_mean']:.3f} & "
                f"{min(folds):.2f}--{max(folds):.2f} & {loco[key]['auc_mean']:.3f} & "
                f"{paired[key]['p_e_mean']:.3f} & {paired[key]['auc_mean']:.3f}"
            )
    return table(
        body, columns="llrrrrr",
        header=("Features & Detector & \\multicolumn{3}{c}{Leave-one-clip-out} & "
                "\\multicolumn{2}{c}{Paired split} \\\\\n\\cmidrule(lr){3-5}\\cmidrule(lr){6-7}\n"
                " & & $P_E$ & range & AUC & $P_E$ & AUC"),
        caption=(f"Learned per-frame steganalysis of the magnitude carrier on {ml['frame_pairs']:,} modified "
                 f"cover/stego frame pairs from {len(ml['clips'])} CIF clips ($P_E=0.5$ is chance). Range: "
                 "minimum and maximum $P_E$ over the held-out clips.").replace(",", "\\,", 1),
        label="tab:steg-ml",
    )


