def _md_table(text: str, heading: str) -> list[list[str]]:
    section = text.split(heading, 1)[1]
    lines = [line for line in section.splitlines() if line.startswith("|")]
    rows = [[cell.strip() for cell in line.strip("|").split("|")] for line in lines]
    return [row for row in rows[2:] if row]


def carrier_table(results: Path) -> str:
    text = (results / "carrier_compare.md").read_text(encoding="utf-8")
    per_case = _md_table(text, "Paired clips:")
    learned = {row[0]: row for row in _md_table(text, "## Learned steganalysis")}
    labels = {"magnitude": "Magnitude LSB", "t1-spread": "T1 sign, same frames", "t1": "T1 sign, 100 frames"}
    body = []
    for carrier in ("magnitude", "t1-spread", "t1"):
        rows = [row for row in per_case if row[1] == carrier]
        if not rows:
            continue

        def span(index: int, digits: int = 1, scale: float = 1.0) -> str:
            values = [float(row[index]) * scale for row in rows]
            return f"{min(values):.{digits}f}--{max(values):.{digits}f}"

        verified = all(row[2] == "yes" for row in rows)
        sign_p = min(float(row[12]) for row in rows)
        ml = learned.get(carrier, ["--"] * 6)
        body.append(
            f"{labels[carrier]} & {len(rows)}/{len(rows) if verified else '?'} & {span(3)} & {span(6)} & "
            f"{span(7)} & {span(8, 4)} & {span(9, 0)} & {span(10, 0)} & {sign_p:.3f} & "
            f"{ml[2]} & {ml[4]} & {ml[3]} & {ml[5]}"
        )
    return table(
        body, columns="lrrrrrrrrrrrr", wide=True,
        header=("Carrier & Verified & kbit/100 fr. & PSNR$_{\\mathrm{mod}}$ & PSNR$_{\\min}$ & SSIM & "
                "Embed (s) & Verify (s) & min Pos.\\ $p$ & \\multicolumn{4}{c}{Learned $P_E$} \\\\\n"
                "\\cmidrule(lr){10-13}\n & & & & & & & & & Coef. & Pixel & Comb. & Comb. \\\\\n"
                " & & & & & & & & & LOCO & LOCO & LOCO & paired"),
        caption=("Carrier comparison through the same pipeline on four CIF clips (City, Coastguard, "
                 "Container, Hall; QP\\,22, registered mode). Ranges are over the four clips. ``Same "
                 "frames'' uses the chunk size of the magnitude run, so both carriers touch the same "
                 "number of frames; ``100 frames'' packs the envelope into one segment. min Pos.\\ $p$: "
                 "smallest per-position sign-test $p$-value over the clips."),
        label="tab:carrier",
    )


# -- density and embedding rule -------------------------------------------- #

def density_table(results: Path) -> str:
    sim = load(results / "embedding_density_sim.json")
    rule = load(results / "embedding_rule_sim.json")
    t1 = load(results / "embedding_t1_vs_magnitude_sim.json")
    body = [
        f"Magnitude LSB replacement, 100\\,\\% & {sim['replacement']['p_e_mean']:.3f} & {sim['replacement']['auc_mean']:.3f}",
        f"Magnitude LSB replacement, 50\\,\\% & {sim['replacement@0.5']['p_e_mean']:.3f} & {sim['replacement@0.5']['auc_mean']:.3f}",
        f"Magnitude LSB replacement, 25\\,\\% & {sim['replacement@0.25']['p_e_mean']:.3f} & {sim['replacement@0.25']['auc_mean']:.3f}",
        f"Magnitude LSB replacement, 10\\,\\% & {sim['replacement@0.1']['p_e_mean']:.3f} & {sim['replacement@0.1']['auc_mean']:.3f}",
        f"Magnitude LSB matching ($\\pm1$), 100\\,\\% & {rule['matching']['p_e_mean']:.3f} & {rule['matching']['auc_mean']:.3f}",
        f"T1 sign flip, 100\\,\\% & {t1['t1_sign']['p_e_mean']:.3f} & {t1['t1_sign']['auc_mean']:.3f}",
        "\\midrule",
    ]
    report = results / "density_report.json"
    if report.exists():
        # density_report.json maps the density ("1", "0.5", ...) to the measured level.
        measured = load(report)
        for density, level in sorted(measured.items(), key=lambda item: -float(item[0])):
            learned = level.get("learned") or {}
            p_e, auc = learned.get("coefficient_fld"), learned.get("coefficient_fld_auc")
            body.append(f"Measured 4CIF E2E, {float(density) * 100:.0f}\\,\\% & "
                        f"{'--' if p_e is None else f'{p_e:.3f}'} & {'--' if auc is None else f'{auc:.3f}'}")
    else:
        for level in (100, 50, 25):
            body.append(f"Measured 4CIF E2E, {level}\\,\\% & {TODO} & {TODO}")
    return table(
        body, columns="lrr",
        header="Embedding (fraction of carriers used) & $P_E$ & AUC",
        caption=("Detectability versus embedding rule and density: leave-one-clip-out, coefficient "
                 "features, FLD ensemble, five CIF clips. The upper rows are simulated on the real carrier "
                 "positions without the patchability filter (hence more detectable than the real runs, "
                 "$P_E=0.40$); they are for relative comparison only. The lower rows are real registered "
                 "E2E runs on City and Harbour 4CIF (leave-one-clip-out over these two clips)."),
        label="tab:density",
    )


