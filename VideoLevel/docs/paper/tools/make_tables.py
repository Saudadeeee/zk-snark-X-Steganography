"""Build the manuscript's result tables from the measured result files.

Reads only existing result files (no experiment is run) and writes
``docs/paper/tables/paper_*.tex``.  Cases that are configured in
``benchmark/latticezk_q2_cases.json`` but have no result yet are emitted as
explicit ``[TODO]`` rows, so a pending experiment is never silently dropped
or estimated.

    python docs/paper/tools/make_tables.py [--results DIR]

``--results`` defaults to ``benchmark/results/q2`` of this checkout.  The
script uses only the standard library.
"""

