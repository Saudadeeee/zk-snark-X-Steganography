def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results", type=Path, default=VIDEO_LEVEL / "benchmark" / "results" / "q2")
    arguments = parser.parse_args()
    results = arguments.results.resolve()
    outputs = {
        "paper_capacity": capacity_table(results),
        "paper_e2e": e2e_table(results),
        "paper_steg_classical": steg_classical_table(results),
        "paper_steg_ml": steg_ml_table(results),
        "paper_carrier": carrier_table(results),
        "paper_density": density_table(results),
        "paper_baselines": baselines_table(results),
    }
    (PAPER / "tables").mkdir(parents=True, exist_ok=True)
    for name, text in outputs.items():
        (PAPER / "tables" / f"{name}.tex").write_text(text, encoding="utf-8")
        print(f"wrote tables/{name}.tex")
    return 0


